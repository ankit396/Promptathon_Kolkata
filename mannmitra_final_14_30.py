# ── 11. Surya Namaskar daily tracker ──────────────────────────────────────────
PRACTICE_LOG: set = set()

def mark_surya_namaskar_done() -> str:
    """Record today's practice and return a streak message."""
    today = datetime.date.today()
    PRACTICE_LOG.add(today.isoformat())
    streak, d = 0, today
    while d.isoformat() in PRACTICE_LOG:
        streak += 1
        d -= datetime.timedelta(days=1)
    if streak <= 1:
        return "✅ Logged for today — that's a great start. 🌞"
    return f"✅ Logged for today! 🔥 {streak}-day streak — keep it going!"

