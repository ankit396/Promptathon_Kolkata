# ── 4. Core LLM caller (with fallback and reasoning hidden) ────────────────
def call_llm(
    messages: List[dict],
    temperature: float = 0.6,
    max_tokens: int = MAX_TOKENS_JOURNAL,
    model: str = PRIMARY_MODEL
) -> str:
    """
    Call the Groq LLM, hiding reasoning tokens and stripping think tags.
    """
    kwargs = dict(
        model=model,
        messages=messages,
        temperature=temperature,
        max_tokens=max_tokens,
    )
    try:
        response = client.chat.completions.create(
            **kwargs,
            extra_body={"reasoning_format": "hidden", "reasoning_effort": "low"},
        )
    except Exception:
        # Fallback if extra_body not supported (old API)
        response = client.chat.completions.create(**kwargs)

    content = response.choices[0].message.content or ""
    content = re.sub(r"<think>.*?</think>", "", content, flags=re.DOTALL).strip()
    return content

def call_llm_safe(
    messages: List[dict],
    temperature: float = 0.6,
    max_tokens: int = MAX_TOKENS_JOURNAL
) -> str:
    """Call LLM with automatic fallback to secondary model on rate limit / not found."""
    try:
        return call_llm(messages, temperature, max_tokens, model=PRIMARY_MODEL)
    except Exception as e:
        err = str(e).lower()
        if any(x in err for x in ("rate", "limit", "quota", "not found")):
            print(f"⚠️ Primary model unavailable — falling back to {FALLBACK_MODEL}")
            return call_llm(messages, temperature, max_tokens, model=FALLBACK_MODEL)
        raise

