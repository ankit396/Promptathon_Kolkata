def _load_font(size: int) -> ImageFont:
    """Load a TrueType font or fallback to default."""
    for name in ("DejaVuSans-Bold.ttf", "DejaVuSans.ttf"):
        try:
            return ImageFont.truetype(name, size)
        except Exception:
            continue
    return ImageFont.load_default()

def generate_motivation_image(
    institute: str,
    custom_name: str,
    days_done: int,
    days_total: int
) -> Image.Image:
    """Generate a motivational image with progress bar."""
    name = (custom_name.strip() if institute == "Custom (type below)" and custom_name else institute)
    try:
        days_done = max(0, int(days_done))
    except Exception:
        days_done = 0
    try:
        days_total = max(1, int(days_total))
    except Exception:
        days_total = 1
    pct = min(100, int(round(100 * days_done / days_total)))

    prompt = (
        f"cinematic warm golden-hour digital painting, a determined young Indian student in "
        f"casual clothes climbing the final stone steps toward a grand, ornate academic gateway "
        f"with classical pillars, the words '{name}' engraved on the archway above, soft sunrise "
        f"light, sense of hope courage and near-achievement, inspirational poster style, highly "
        f"detailed, painterly, no readable extra text, no logos"
    )
    seed = random.randint(1, 999999)
    url = ("https://image.pollinations.ai/prompt/" + requests.utils.quote(prompt)
           + f"?width=1024&height=683&nologo=true&seed={seed}")

    try:
        resp = requests.get(url, timeout=45)
        img = Image.open(io.BytesIO(resp.content)).convert("RGB")
    except Exception:
        # Fallback placeholder
        img = Image.new("RGB", (1024, 683), (255, 247, 230))
        d = ImageDraw.Draw(img)
        d.text((40, 40), "(Image service unreachable — showing placeholder card)",
               fill=(120, 90, 40), font=_load_font(26))

    draw = ImageDraw.Draw(img)
    bar_x, bar_y, bar_w, bar_h = 56, img.height - 86, img.width - 112, 30
    draw.rounded_rectangle([bar_x, bar_y, bar_x + bar_w, bar_y + bar_h],
                           radius=15, fill=(255, 255, 255))
    fill_w = max(30, int(bar_w * pct / 100))
    draw.rounded_rectangle([bar_x, bar_y, bar_x + fill_w, bar_y + bar_h],
                           radius=15, fill=(255, 140, 0))
    caption = f"You're {pct}% of the way to {name} -- just a little closer!"
    draw.text((bar_x, bar_y - 46), caption, fill=(25, 25, 25), font=_load_font(28))
    return img

